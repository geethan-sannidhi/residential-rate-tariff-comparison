"""Compare calculator output with independently published bills; writes docs/VALIDATION.md."""
import json, sys
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from tariffcalc import load_tariff, monthly_bill, annual_average_bill  # noqa: E402


def run():
    ref = json.loads((ROOT / "reference" / "external_bills.json").read_text())
    rows = []
    for c in ref["checks"]:
        t = load_tariff(ROOT / "data" / f"{c['tariff']}.json")
        got = annual_average_bill(t, c["kwh"]) if c.get("annual_average") else monthly_bill(t, c["kwh"]).total
        exp = Decimal(str(c["expected"]))
        rows.append({**c, "utility": t.utility, "got": got, "diff": got - exp})
    return ref, rows


if __name__ == "__main__":
    ref, rows = run()
    out = ["# Validation against published bills", "",
           "Generated by `scripts/validate.py`. Expected values are other organizations' published residential bills, "
           "before gross receipts tax and franchise fees.", "",
           "| Utility | kWh | Calculator | Published | Difference | Source | Notes |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        note = r.get("known_difference") or r["note"]
        out.append(f"| {r['utility']} | {r['kwh']:,} | ${r['got']} | ${r['expected']:.2f} | {r['diff']:+} | {r['source']} | {note} |")
    exact = sum(1 for r in rows if r["diff"] == 0)
    out += ["", f"{exact} of {len(rows)} checks match to the cent.", "",
            "No independent check is available yet for JEA, City of Tallahassee or OUC: the latest FMEA edition "
            "(September 2026) predates their October-November 2026 rate changes.", "", "## Sources"]
    out += [f"- **{k}**: {v}" for k, v in ref["sources"].items()]
    (ROOT / "docs" / "VALIDATION.md").write_text("\n".join(out) + "\n")
    print("\n".join(out[5:5 + len(rows) + 2]))
