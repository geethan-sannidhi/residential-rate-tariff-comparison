"""Validate the calculator against FMEA's published 2026 monthly bills, using the rate version in effect each month.

Rate versions live in data/history/<schedule>@<first month>.json. Each lists the months for which a primary source
(tariff sheet, utility rate insert, PSC order or PSC billing table) documents that version ('months_documented') and
months where only the change date is uncertain ('months_inferred'). Only documented months count toward validation.
Writes outputs/fmea_validation.csv and docs/BILL_VALIDATION.md.
"""
import csv
import json
import sys
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from tariffcalc import load_tariff, monthly_bill  # noqa: E402

ROUNDING = Decimal("0.05")
MISMATCH_NOTES = {
    ("duke_rs1", "2026-01"): "FMEA's January bill is about 3.2 cents/kWh higher than the January rates documented by Duke's tariff, the 2026 fuel order "
                             "and the PSC's March 2026 table (which covers January-December 2026 and shows no storm charge for Duke). The size and timing "
                             "are consistent with Duke's storm cost recovery surcharge for the 2024 hurricanes, and FMEA's Duke bills rose by a similar amount from March 2025, "
                             "but no tariff for that surcharge was retrieved, so the difference is left unexplained.",
    ("duke_rs1", "2026-02"): "FMEA's February bill is 6 to 16 cents higher than the documented winter rates (the PSC's March table shows Duke's December-February "
                             "base charges as $101.35 at 1,000 kWh, which the calculator reproduces). The source of the small difference was not found.",
}  # FMEA rounds each bill component to the cent before adding them
NAMES = {"fpl_rs1": "FPL", "fpl_nwfl_rs1": "FPL NW Florida", "duke_rs1": "Duke", "teco_rs": "Tampa Electric", "fpuc_rs": "FPUC"}


def versions():
    out = {}
    for p in sorted((ROOT / "data" / "history").glob("*.json")):
        d = json.loads(p.read_text())
        t = load_tariff(p)
        key = p.stem.split("@")[0]
        for m in d["months_documented"]:
            out[(key, m)] = (t, p.stem, "documented")
        for m in d.get("months_inferred", []):
            out[(key, m)] = (t, p.stem, "inferred")
    return out


def run():
    ref = json.loads((ROOT / "reference" / "fmea_2026.json").read_text())["rows"]
    V = versions()
    rows = []
    for r in ref:
        v = V.get((r["tariff"], r["edition"]))
        if v is None:
            rows.append({**r, "version": "", "basis": "no rate version", "calculator": None, "difference": None, "result": "not checked"})
            continue
        t, name, basis = v
        got = monthly_bill(t, r["kwh"], month=int(r["edition"][5:]), days=30).total
        diff = got - Decimal(str(r["total"]))
        result = "exact" if diff == 0 else ("within rounding" if abs(diff) <= ROUNDING else "mismatch")
        rows.append({**r, "version": name, "basis": basis, "calculator": float(got), "difference": float(diff), "result": result})
    return rows


def write(rows):
    fields = ["tariff", "edition", "kwh", "total", "calculator", "difference", "result", "basis", "version", "source"]
    with open(ROOT / "outputs" / "fmea_validation.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    doc_rows = [r for r in rows if r["basis"] == "documented"]
    inf_rows = [r for r in rows if r["basis"] == "inferred"]
    count = lambda rs, res: sum(1 for r in rs if r["result"] == res)
    lines = [
        "# Validation against 2026 published bills",
        "",
        "Generated by `scripts/validate_history.py`. Each 2026 monthly edition of the Florida Municipal Electric Association's "
        "Electric Bill Comparison publishes residential bills at 1,000, 1,200 and 2,500 kWh. Each published bill is recalculated "
        "with the calculator, using the rate version in effect that month (`data/history/`), and compared with the published total "
        "(before gross receipts tax and franchise fees).",
        "",
        "A check counts only when a primary source (tariff sheet, utility rate insert, PSC order or PSC billing table) documents the "
        "rate version for that month. FMEA rounds each bill component to the cent before adding them, so differences of a few cents "
        "are reported as *within rounding*.",
        "",
        "## Result",
        "",
        f"- **{len(doc_rows)} documented checks**: {count(doc_rows, 'exact')} exact, {count(doc_rows, 'within rounding')} within rounding "
        f"(largest difference {max([abs(r['difference']) for r in doc_rows if r['result'] == 'within rounding'] or [0]) * 100:.0f} cents), "
        f"{count(doc_rows, 'mismatch')} mismatches. {count(doc_rows, 'exact') + count(doc_rows, 'within rounding')} of {len(doc_rows)} match.",
        f"- {len(inf_rows)} further checks use months where the rate change date is inferred: {count(inf_rows, 'exact')} exact, "
        f"{count(inf_rows, 'within rounding')} within rounding, {count(inf_rows, 'mismatch')} mismatches. These are not counted.",
        "- Duke's September bills confirm that its second 2026 base-rate change, filed as effective September 1, was not yet in FMEA's or "
        "the PSC's September figures; both show June base rates with the new asset securitization charge.",
        "- Not checked: the three municipal utilities (JEA, Tallahassee, OUC), whose past rate sheets were not available, and 2025 editions.",
        "",
        "| Schedule | Months documented | Checks | Exact | Within rounding | Mismatch |",
        "|---|---|---|---|---|---|",
    ]
    for k, nm in NAMES.items():
        rs = [r for r in doc_rows if r["tariff"] == k]
        months = sorted({r["edition"] for r in rs})
        lines.append(f"| {nm} | {', '.join(m[5:] for m in months)} | {len(rs)} | {count(rs, 'exact')} | {count(rs, 'within rounding')} | {count(rs, 'mismatch')} |")
    mism = [r for r in rows if r["result"] == "mismatch"]
    if mism:
        lines += ["", "## Mismatches", "", "| Schedule | Edition | kWh | Published | Calculator | Difference | Basis |", "|---|---|---|---|---|---|---|"]
        for r in mism:
            lines.append(f"| {NAMES[r['tariff']]} | {r['edition']} | {r['kwh']:,} | ${r['total']:.2f} | ${r['calculator']:.2f} | {r['difference']:+.2f} | {r['basis']} |")
        lines.append("")
        for (k, m), note in MISMATCH_NOTES.items():
            if any(r["tariff"] == k and r["edition"] == m for r in mism):
                lines.append(f"- **{NAMES[k]}, {m}:** {note}")
    lines += ["", "## Rate versions used", "", "| Version | Months documented | Months inferred | Note |", "|---|---|---|---|"]
    for p in sorted((ROOT / "data" / "history").glob("*.json")):
        d = json.loads(p.read_text())
        note = d.get("version_note") or " ".join(d.get("notes", [])[:1])
        lines.append(f"| `{p.stem}` | {', '.join(m[5:] for m in d['months_documented'])} | {', '.join(m[5:] for m in d.get('months_inferred', [])) or '-'} | {note} |")
    lines += ["", "Every published bill, with its source edition, is in `outputs/fmea_validation.csv`; the extracted FMEA values are in `reference/fmea_2026.json`."]
    (ROOT / "docs" / "BILL_VALIDATION.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    rows = run()
    write(rows)
    d = [r for r in rows if r["basis"] == "documented"]
    print(f"{len(d)} documented checks: " + ", ".join(f"{k} {sum(1 for r in d if r['result'] == k)}" for k in ("exact", "within rounding", "mismatch")))
    for r in rows:
        if r["result"] == "mismatch":
            print("  mismatch", r["tariff"], r["edition"], r["kwh"], r["total"], r["calculator"], r["difference"], r["basis"])
